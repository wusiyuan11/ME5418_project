"""Clipped PPO only: policy-gradient objective and learned value regression."""
import math
import numpy as np
import torch
from torch.nn import functional as F


def update(agent,batch,fraction):
    cfg,model = agent.config,agent.model
    rate = .1 + .9*(1-fraction)
    for optimizer,initial in ((agent.policy_optimizer,cfg.learning_rate),
                              (agent.value_optimizer,cfg.value_learning_rate)):
        for group in optimizer.param_groups:
            group['lr'] = initial*rate
    advantage = batch['advantages']
    # Advantages were computed from reward + value predictions during rollout.
    # They are training targets, NOT extra actor inputs or expert action labels.
    advantage = (advantage-advantage.mean())/(advantage.std(unbiased=False)+1e-8)
    rows,stopped,policy_steps,value_steps = [],False,0,0
    actor_parameters = list(model.actor.parameters())+[model.log_std]
    for _ in range(cfg.epochs):
        for indices in torch.randperm(len(advantage)).split(cfg.batch_size):
            probability,value = model.evaluate(batch['observations'][indices],batch['latents'][indices])
            log_ratio = probability-batch['old_log_probs'][indices]
            ratio = log_ratio.exp()
            # KL is an empirical minibatch estimate, not a hard trust-region
            # guarantee. Once triggered, stop the actor for this whole update.
            kl = ((ratio-1)-log_ratio).mean()
            if kl.detach().item() > 1.5*cfg.target_kl:
                stopped = True
            policy_loss = -torch.minimum(ratio*advantage[indices],
                ratio.clamp(1-cfg.clip_range,1+cfg.clip_range)*advantage[indices]).mean()
            value_loss = F.mse_loss(value,batch['returns'][indices])
            # Two objectives: PPO changes action probabilities; the critic
            # predicts returns generated by interaction. No correct action
            # target, PID correction or behavior-cloning loss is supplied.
            if not torch.isfinite(policy_loss+value_loss):
                raise FloatingPointError('Non-finite PPO loss')
            if not stopped:
                # Optional entropy is of the latent Normal, explicitly named.
                entropy = (model.log_std + .5*math.log(2*math.pi*math.e)).sum()
                actor_loss = policy_loss-cfg.entropy_coef*entropy
                agent.policy_optimizer.zero_grad()
                actor_loss.backward()
                norm = torch.nn.utils.clip_grad_norm_(actor_parameters,.5)
                if not torch.isfinite(norm):
                    raise FloatingPointError('Non-finite policy gradient')
                agent.policy_optimizer.step()
                with torch.no_grad():
                    model.log_std.clamp_(-4.5,.2)
                policy_steps += 1
            # Separate networks/optimizers: stopping policy updates does not
            # prevent fitting the critic on the same on-policy return targets.
            agent.value_optimizer.zero_grad()
            value_loss.backward()
            norm = torch.nn.utils.clip_grad_norm_(model.critic.parameters(),.5)
            if not torch.isfinite(norm):
                raise FloatingPointError('Non-finite value gradient')
            agent.value_optimizer.step()
            value_steps += 1
            rows.append([policy_loss.item(),value_loss.item(),kl.item(),
                         ((ratio.detach()-1).abs()>cfg.clip_range).float().mean().item()])
    metrics = np.mean(rows,axis=0).tolist()
    return dict(zip(('policy_loss','value_loss','approx_kl','clip_fraction'),metrics)) | {
        'policy_optimizer_steps':policy_steps,'value_optimizer_steps':value_steps,
        'kl_early_stop':stopped,'latent_std_mean':float(model.log_std.detach().exp().mean()),
        'actor_learning_rate':agent.policy_optimizer.param_groups[0]['lr']}
